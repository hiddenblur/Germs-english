"""Write decomp/germs.yaml with one splat subsegment per object.

Usage: python -I tools/gen_splat.py

Objects of the .text range 0x80173054-0x801D7330, from two sources:
  - decomp/objects.txt (tools/objmap.py): Psy-Q library modules found whole in the EXE  -> `asm` lib_<LIB>_<MODULE>
  - decomp/functions.txt + the compiled C in decomp/src (tools/build_exe.py): functions with C -> `c` <name>
  - everything between them is unmatched: `asm` game_<addr> (a run of code, not yet split into functions' files)
.rdata, .data/.sdata and .bss stay one segment each: their per-object owners are not known yet.
The generated asm and linker script are gitignored (game code); this yaml has only addresses and names.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_exe

ROOT = build_exe.ROOT
TEXT = (0x80173054, 0x801D7330)
HEADER = """# splat config for SLPS_021.07, generated by tools/gen_splat.py (do not edit by hand).
# Layout comes from the EXE itself (see docs/decomp-setup.md): .rdata 0x80170000-0x80173054, .text to 0x801D7330,
# .data/.sdata to 0x801DFE50, bss 0x801DFE50-0x801E7A10 (zeroed by __SN_ENTRY_POINT at 0x801C8840), gp = 0x801DFC58.
options:
  platform: psx
  basename: slps_021
  base_path: .
  target_path: ../extracted/files/SLPS_021.07
  asm_path: asm
  src_path: splat_src
  build_path: build
  compiler: GCC
  gp_value: 0x801DFC58
  symbol_addrs_path: symbol_addrs.txt
  ld_script_path: slps_021.ld
  find_file_boundaries: false
  asm_function_macro: glabel
  generate_asm_macros_files: true
  section_order: [".rodata", ".text", ".data", ".bss"]
  use_legacy_include_asm: false
  disassemble_all: true
segments:
  - name: header
    type: bin
    start: 0x0
    size: 0x800
  - name: main
    type: code
    start: 0x800
    vram: 0x80170000
    bss_size: 0x7BC0
    subsegments:
      - [0x800, rodata, rdata]
"""
FOOTER = """      - [0x67B30, data, data]
      - { start: 0x70650, type: bss, name: bss, vram: 0x801DFE50 }
  - [0x70800]
"""


def objects():
    """Sorted [(ram start, size, kind, name)] for the whole text range, with asm filling the gaps."""
    found = []
    for line in (ROOT / "decomp" / "objects.txt").read_text().splitlines():
        if line and not line.startswith("#"):
            addr, size, lib, mod, *_ = line.split()
            found.append((int(addr, 16), int(size, 16), "asm", f"lib_{lib.split('.')[0]}_{mod}"))
    _, _, results = build_exe.build()
    found += [(addr, words * 4, "c", name) for name, addr, words, _ in results]
    found.sort()
    out, pos = [], TEXT[0]
    for addr, size, kind, name in found:
        if addr < pos:
            sys.exit(f"{name} (0x{addr:08X}) overlaps the previous object ending at 0x{pos:08X}")
        if addr > pos:
            out.append((pos, addr - pos, "asm", f"game_{pos:08X}"))
        out.append((addr, size, kind, name))
        pos = addr + size
    if pos < TEXT[1]:
        out.append((pos, TEXT[1] - pos, "asm", f"game_{pos:08X}"))
    return out


def main():
    objs = objects()
    lines = [f"      - [0x{a - 0x80170000 + 0x800:X}, {kind}, {name}]" for a, _, kind, name in objs]
    (ROOT / "decomp" / "germs.yaml").write_text(HEADER + "\n".join(lines) + "\n" + FOOTER, newline="\n")
    n = {k: sum(o[2] == k for o in objs) for k in ("c", "asm")}
    print(f"{len(objs)} text objects ({n['c']} c, {n['asm']} asm) -> decomp/germs.yaml")


if __name__ == "__main__":
    main()
