def _load():
    glyphs = {}
    for ch, art in _GLYPHS.items():
        rows = art.split("/")
        width = len(rows[0])
        if len(rows) > HEIGHT or any(len(r) != width for r in rows):
            raise ValueError(f"glyph {ch!r} is malformed")
        rows += ["." * width] * (HEIGHT - len(rows))
        glyphs[ch] = [[c == "#" for c in r] for r in rows]
    return glyphs


GLYPHS = _load()


def text_width(text):
    """Pixel width of a line, with 1 px between glyphs."""
    if not text:
        return 0
    return sum(len(GLYPHS[c][0]) for c in text) + len(text) - 1


def check_chars(text):
    missing = sorted({c for c in text if c != "\n" and c not in GLYPHS})
    if missing:
        raise ValueError(f"no glyph for {''.join(missing)!r} in the image font")


def wrap(text, width):
    """Word-wrap to a pixel width; explicit newlines are kept."""
    check_chars(text)
    lines = []
    for para in text.split("\n"):
        line = ""
        for word in para.split(" "):
            candidate = word if not line else line + " " + word
            if text_width(candidate) <= width:
                line = candidate
            else:
                if text_width(word) > width:
                    raise ValueError(f"word {word!r} is wider than {width} px")
                lines.append(line)
                line = word
        lines.append(line)
    return lines


def draw(pixels, stride, x, y, text, ink):
    """Draw one line with its top at row y; returns the x after the last glyph."""
    for c in text:
        g = GLYPHS[c]
        for r, row in enumerate(g):
            for i, on in enumerate(row):
                if on:
                    pixels[(y + r) * stride + x + i] = ink
        x += len(g[0]) + 1
    return x
