"""Write decomp/symbol_addrs.txt from the library match list (extracted/libmatch.txt).

Run `python -I tools/libmatch.py extracted/files/SLPS_021.07 <Lib44 LIBs> > extracted/libmatch.txt` first.
Addresses with several names (aliases, or short functions that match in many places) are
resolved by taking the name that matches at the fewest addresses; the others go in a comment.
Functions found at more than 3 addresses are skipped: they are too short to identify.
"""
import collections
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXTRA = {
    0x8018BDE8: 'main',
}

by_addr = collections.defaultdict(set)
count = collections.Counter()
for line in (ROOT / 'extracted' / 'libmatch.txt').read_text().splitlines():
    if line.startswith('##'):
        continue
    lib, mod, fn, addr, words = line.split()
    if fn.startswith('<'):
        continue
    by_addr[int(addr, 16)].add((fn, int(words), lib))
    count[fn] += 1

out = ['// generated by tools/gen_symbols.py; do not edit']
used = set()
for addr in sorted(by_addr):
    cands = sorted(by_addr[addr], key=lambda c: (count[c[0]], c[0]))
    fn, words, lib = cands[0]
    cands = [c for c in cands if c[0] not in used]
    if not cands or count[cands[0][0]] > 3:
        continue
    fn, words, lib = cands[0]
    used.add(fn)
    alias = ' (also ' + ', '.join(c[0] for c in cands[1:3]) + ')' if len(cands) > 1 else ''
    out.append('%s = 0x%08X; // type:func size:0x%X%s' % (fn, addr, words * 4, alias))
for addr, fn in EXTRA.items():
    out.append('%s = 0x%08X; // type:func' % (fn, addr))
(ROOT / 'decomp' / 'symbol_addrs.txt').write_text('\n'.join(out) + '\n')
print(len(out) - 1, 'symbols')
