"""Re-run every C file in decomp/src and refresh the committed status files.

Usage: python -I tools/decomp_status.py

- decomp/flags.txt: per function, MATCH / REGS / NONE for each compiler (sdk, 2.7.2, 2.8.1)
- tests/test_cc.py: the MATCHING table (functions that match with the default compiler and the file's
  own cc-flags must keep matching)
"""
import collections
import glob
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY = [sys.executable, "-I", str(ROOT / "tools" / "cc_check.py")]
files = sorted(glob.glob(str(ROOT / "decomp" / "src" / "*.c")))


def run(*args):
    return subprocess.run(PY + list(args), capture_output=True, text=True).stdout


def which(compiler):
    status = {}
    for f in files:
        for line in run(f, "--which-flags", "--cc1", compiler).splitlines():
            m = re.match(r"(\w+) @ 0x([0-9A-F]{8}): (.*)", line.strip())
            if m:
                r = m.group(3)
                st = "NONE" if r.startswith("no flag") else "REGS" if r.startswith("registers") else "MATCH"
                status[m.group(1)] = (m.group(2), st, r)
    return status


res = {c: which(c) for c in ("sdk", "2.7.2", "2.8.1")}
B = res["2.8.1"]
print({c: dict(collections.Counter(v[1] for v in r.values())) for c, r in res.items()})
with open(ROOT / "decomp" / "flags.txt", "w", newline="\n") as f:
    f.write("# Per function: does the C in decomp/src reproduce the retail bytes with each compiler?\n"
            "#   sdk = psyq/bin/CC1PSX.EXE (gcc 2.95.2); 2.7.2 / 2.8.1 = old-gcc psx builds (tools/oldgcc)\n"
            "# MATCH = byte-identical (relocations masked), REGS = same code, other registers, NONE = differs.\n"
            "# Generated by: python -I tools/decomp_status.py\n"
            "# addr name sdk 2.7.2 2.8.1  (2.8.1 flag sets that match)\n")
    for k, (a, st, r) in sorted(B.items(), key=lambda x: x[1][0]):
        fl = ",".join(x.strip().replace(" ", "") for x in r.split("|")) if st == "MATCH" else ""
        f.write(f"{a} {k} {res['sdk'][k][1]} {res['2.7.2'][k][1]} {st} {fl}\n")

by = {}
for fn in files:
    names = [l.split(" @")[0] for l in run(fn).splitlines() if l.endswith(" MATCH")]
    if names:
        by[Path(fn).relative_to(ROOT).as_posix()] = names
p = ROOT / "tests" / "test_cc.py"
s = p.read_text(encoding="utf8", newline="")
nl = "\r\n" if "\r\n" in s else "\n"
s = s.replace("\r\n", "\n")
a = s.index("MATCHING = {")
b = s.index("\n}\n", a) + 3
body = "MATCHING = {\n" + "".join('    "%s": [%s],\n' % (k, ", ".join('"%s"' % n for n in v)) for k, v in by.items()) + "}\n"
p.write_text(s[:a] + body + s[b:], encoding="utf8", newline="")
print(sum(len(v) for v in by.values()), "functions pinned in tests/test_cc.py")
